# Calibration helpers
# ---------------------------------------------------------------------
def wilson_interval(k, n, z=1.959963984540054):
    if n <= 0:
        return np.nan, np.nan
    phat = k / n
    denom = 1.0 + z * z / n
    centre = (phat + z * z / (2.0 * n)) / denom
    half = (
        z
        * np.sqrt(phat * (1.0 - phat) / n + z * z / (4.0 * n * n))
        / denom
    )
    return centre - half, centre + half


def quantile_calibration_points(y: np.ndarray, p: np.ndarray, n_bins: int = 10) -> pd.DataFrame:
    frame = pd.DataFrame({"y": y.astype(int), "p": p.astype(float)})
    frame["bin"] = pd.qcut(frame["p"], q=n_bins, duplicates="drop")

    rows = []
    for _, g in frame.groupby("bin", observed=True, sort=True):
        n = int(len(g))
        k = int(g["y"].sum())
        obs = float(g["y"].mean())
        pred = float(g["p"].mean())
        lo, hi = wilson_interval(k, n)
        rows.append(
            {
                "mean_predicted": pred,
                "observed": obs,
                "ci_low": lo,
                "ci_high": hi,
                "n": n,
            }
        )

    return pd.DataFrame(rows)


