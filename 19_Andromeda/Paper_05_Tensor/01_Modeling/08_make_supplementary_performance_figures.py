METRIC_ALIASES = {
    "average_precision": ["average_precision", "ap"],
    "brier": ["brier", "brier_score"],
    "roc_auc": ["roc_auc", "auroc"],
    "mae": ["mae"],
    "rmse": ["rmse"],
}


def metric_mask(df: pd.DataFrame, metric_name: str) -> pd.Series:
    candidates = METRIC_ALIASES.get(metric_name, [metric_name])
    return df["metric"].isin(candidates)


def find_ci(
    ci: pd.DataFrame,
    *,
    landmark: int,
    outcome: str,
    variant: str,
    cohort: str,
    metric: str,
):
    row = ci.loc[
        ci["landmark_hour"].eq(landmark)
        & ci["outcome"].eq(outcome)
        & ci["variant"].eq(variant)
        & ci["cohort"].eq(cohort)
        & metric_mask(ci, metric)
    ]
    if row.empty:
        return None
    if len(row) != 1:
        raise ValueError(
            f"Expected one bootstrap CI row for "
            f"{landmark}h/{outcome}/{variant}/{cohort}/{metric}, found {len(row)}."
        )
    r = row.iloc[0]
    return float(r["estimate"]), float(r["ci_low"]), float(r["ci_high"])


