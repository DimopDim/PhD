# Smart legend placement
# ---------------------------------------------------------------------
def _count_points_inside_bbox(points_disp: np.ndarray, bbox) -> int:
    if points_disp is None or len(points_disp) == 0:
        return 0
    x = points_disp[:, 0]
    y = points_disp[:, 1]
    inside = (
        (x >= bbox.x0) & (x <= bbox.x1) &
        (y >= bbox.y0) & (y <= bbox.y1)
    )
    return int(np.sum(inside))


def _collect_display_points(ax):
    pts_all = []

    # Lines
    for line in ax.lines:
        try:
            x = np.asarray(line.get_xdata(), dtype=float)
            y = np.asarray(line.get_ydata(), dtype=float)
        except Exception:
            continue
        m = np.isfinite(x) & np.isfinite(y)
        if np.any(m):
            pts = np.column_stack([x[m], y[m]])
            pts_all.append(ax.transData.transform(pts))

    # Scatter / errorbar collections / hexbin
    for coll in ax.collections:
        try:
            offsets = coll.get_offsets()
            if offsets is None:
                continue
            offsets = np.asarray(offsets, dtype=float)
            if offsets.ndim == 2 and offsets.shape[1] == 2 and len(offsets) > 0:
                m = np.isfinite(offsets[:, 0]) & np.isfinite(offsets[:, 1])
                if np.any(m):
                    pts_all.append(ax.transData.transform(offsets[m]))
        except Exception:
            continue

    if not pts_all:
        return np.empty((0, 2))
    return np.vstack(pts_all)


def place_legend_smart(ax, handles=None, labels=None, **legend_kwargs):
    """
    Try multiple legend positions and select the one with minimum overlap
    with plotted content in display coordinates.
    """
    fig = ax.figure
    fig.canvas.draw()
    renderer = fig.canvas.get_renderer()

    if handles is None or labels is None:
        handles, labels = ax.get_legend_handles_labels()

    if not handles:
        return None

    candidate_locs = [
        "upper right",
        "upper left",
        "lower left",
        "lower right",
        "center left",
        "center right",
        "upper center",
        "lower center",
    ]

    plotted_points = _collect_display_points(ax)

    best_loc = None
    best_score = None

    for loc in candidate_locs:
        tmp_leg = ax.legend(
            handles,
            labels,
            loc=loc,
            frameon=True,
            fancybox=True,
            framealpha=0.90,
            borderpad=0.35,
            handlelength=2.0,
            **legend_kwargs,
        )
        fig.canvas.draw()
        bbox = tmp_leg.get_window_extent(renderer=renderer).expanded(1.03, 1.08)

        score = _count_points_inside_bbox(plotted_points, bbox)

        # Mild penalty for very central locations
        if "center" in loc:
            score += 3

        tmp_leg.remove()

        if best_score is None or score < best_score:
            best_score = score
            best_loc = loc

    final_leg = ax.legend(
        handles,
        labels,
        loc=best_loc if best_loc is not None else "best",
        frameon=True,
        fancybox=True,
        framealpha=0.90,
        borderpad=0.35,
        handlelength=2.0,
        **legend_kwargs,
    )
    return final_leg


