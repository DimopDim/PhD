# Figure S3: 24h mortality ROC + PR
# ---------------------------------------------------------------------
def figure_s3_discrimination(
    modeling_root: Path,
    ci: pd.DataFrame,
    output_dir: Path,
    landmark: int = 24,
) -> None:
    fig, axes = plt.subplots(2, 2, figsize=(7.4, 6.2))

    for col, cohort in enumerate(COHORTS):
        prevalence = None

        # ROC
        roc_handles = []
        roc_labels = []

        for variant in VARIANTS:
            pred = load_prediction(modeling_root, landmark, "mortality", variant, cohort)
            y = pred["y_true"].to_numpy(dtype=int)
            p = pred["prediction_calibrated"].to_numpy(dtype=float)

            prevalence = float(np.mean(y))

            fpr, tpr, _ = roc_curve(y, p)
            auc_ci = find_ci(
                ci,
                landmark=landmark,
                outcome="mortality",
                variant=variant,
                cohort=cohort,
                metric="roc_auc",
            )
            if auc_ci is None:
                auc_val = roc_auc_score(y, p)
                label = f"{VARIANT_LABEL[variant]}: {auc_val:.3f}"
            else:
                label = f"{VARIANT_LABEL[variant]}: {auc_ci[0]:.3f} [{auc_ci[1]:.3f}-{auc_ci[2]:.3f}]"

            line, = axes[0, col].plot(
                fpr,
                tpr,
                linewidth=1.7,
                color=COLORS[variant],
                label=label,
            )
            roc_handles.append(line)
            roc_labels.append(label)

        ref_line, = axes[0, col].plot(
            [0, 1],
            [0, 1],
            linestyle="--",
            linewidth=1.1,
            color=COLORS["reference"],
            label="Reference",
        )
        roc_handles.append(ref_line)
        roc_labels.append("Reference")

        axes[0, col].set_xlim(0, 1)
        axes[0, col].set_ylim(0, 1.02)
        axes[0, col].set_xlabel("False-positive rate")
        axes[0, col].set_ylabel("True-positive rate")
        axes[0, col].set_title(f"ROC — {COHORT_LABEL[cohort]}")
        axes[0, col].grid(True)
        place_legend_smart(axes[0, col], handles=roc_handles, labels=roc_labels)

        # PR
        pr_handles = []
        pr_labels = []

        for variant in VARIANTS:
            pred = load_prediction(modeling_root, landmark, "mortality", variant, cohort)
            y = pred["y_true"].to_numpy(dtype=int)
            p = pred["prediction_calibrated"].to_numpy(dtype=float)

            precision, recall, _ = precision_recall_curve(y, p)
            ap_ci = find_ci(
                ci,
                landmark=landmark,
                outcome="mortality",
                variant=variant,
                cohort=cohort,
                metric="average_precision",
            )
            if ap_ci is None:
                ap_val = average_precision_score(y, p)
                label = f"{VARIANT_LABEL[variant]}: {ap_val:.3f}"
            else:
                label = f"{VARIANT_LABEL[variant]}: {ap_ci[0]:.3f} [{ap_ci[1]:.3f}-{ap_ci[2]:.3f}]"

            line, = axes[1, col].plot(
                recall,
                precision,
                linewidth=1.7,
                color=COLORS[variant],
                label=label,
            )
            pr_handles.append(line)
            pr_labels.append(label)

        prev_line = axes[1, col].axhline(
            prevalence,
            linestyle="--",
            linewidth=1.1,
            color=COLORS["reference"],
            label=f"Prevalence: {prevalence:.3f}",
        )
        pr_handles.append(prev_line)
        pr_labels.append(f"Prevalence: {prevalence:.3f}")

        axes[1, col].set_xlim(0, 1)
        axes[1, col].set_ylim(0, 1.02)
        axes[1, col].set_xlabel("Recall")
        axes[1, col].set_ylabel("Precision")
        axes[1, col].set_title(f"Precision–recall — {COHORT_LABEL[cohort]}")
        axes[1, col].grid(True)
        place_legend_smart(axes[1, col], handles=pr_handles, labels=pr_labels)

    for idx, ax in enumerate(axes.flat):
        add_panel_label(ax, f"({chr(ord('a') + idx)})")

    save_all(fig, output_dir, "S3_mortality_discrimination_24h")


