# Figure S4: 24h calibration
# ---------------------------------------------------------------------
def figure_s4_calibration(
    modeling_root: Path,
    output_dir: Path,
    landmark: int = 24,
) -> None:
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 3.5), sharex=True, sharey=True)

    for col, cohort in enumerate(COHORTS):
        ax = axes[col]

        ref, = ax.plot(
            [0, 1],
            [0, 1],
            linestyle="--",
            linewidth=1.1,
            color=COLORS["reference"],
            label="Ideal calibration",
        )

        handles = [ref]
        labels = ["Ideal calibration"]

        for variant in VARIANTS:
            pred = load_prediction(modeling_root, landmark, "mortality", variant, cohort)
            y = pred["y_true"].to_numpy(dtype=int)
            p = pred["prediction_calibrated"].to_numpy(dtype=float)

            cal = quantile_calibration_points(y, p, n_bins=10)
            yerr = np.vstack(
                [
                    cal["observed"].to_numpy() - cal["ci_low"].to_numpy(),
                    cal["ci_high"].to_numpy() - cal["observed"].to_numpy(),
                ]
            )

            eb = ax.errorbar(
                cal["mean_predicted"],
                cal["observed"],
                yerr=yerr,
                marker="o",
                markersize=4.5,
                linewidth=1.5,
                capsize=2.5,
                color=COLORS[variant],
                label=VARIANT_LABEL[variant],
            )
            handles.append(eb)
            labels.append(VARIANT_LABEL[variant])

        ax.set_xlim(0, 1)
        ax.set_ylim(0, 1)
        ax.set_xlabel("Mean predicted probability")
        ax.set_ylabel("Observed event frequency")
        ax.set_title(COHORT_LABEL[cohort])
        ax.grid(axis="both", alpha=0.20)
        place_legend_smart(ax, handles=handles, labels=labels)
        add_panel_label(ax, f"({chr(ord('a') + col)})")

    save_all(fig, output_dir, "S4_mortality_calibration_24h")


