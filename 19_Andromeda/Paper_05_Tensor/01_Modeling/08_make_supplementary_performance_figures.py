def prediction_path(
    modeling_root: Path,
    landmark: int,
    outcome: str,
    variant: str,
    cohort: str,
) -> Path:
    return (
        modeling_root
        / "results"
        / f"landmark_{landmark:03d}h"
        / outcome
        / variant
        / f"predictions_{cohort}.parquet"
    )


def load_prediction(
    modeling_root: Path,
    landmark: int,
    outcome: str,
    variant: str,
    cohort: str,
) -> pd.DataFrame:
    path = prediction_path(modeling_root, landmark, outcome, variant, cohort)
    if not path.is_file():
        raise FileNotFoundError(path)

    df = pd.read_parquet(path)
    required_common = {"patient_id", "stay_id", "y_true"}
    missing = required_common.difference(df.columns)
    if missing:
        raise ValueError(f"{path} missing columns: {sorted(missing)}")

    if df["patient_id"].astype(str).duplicated().any():
        raise ValueError(f"{path}: duplicate patient_id rows detected.")

    if outcome == "mortality":
        required = {"prediction_calibrated"}
        missing = required.difference(df.columns)
        if missing:
            raise ValueError(f"{path} missing columns: {sorted(missing)}")

        out = df[["patient_id", "stay_id", "y_true", "prediction_calibrated"]].copy()
        out["y_true"] = pd.to_numeric(out["y_true"], errors="coerce")
        out["prediction_calibrated"] = pd.to_numeric(
            out["prediction_calibrated"], errors="coerce"
        )

        # eICU patients with unknown hospital outcome remain in prediction files
        # but are not evaluable for mortality metrics/plots.
        known = (
            np.isfinite(out["y_true"].to_numpy(dtype=float))
            & np.isfinite(out["prediction_calibrated"].to_numpy(dtype=float))
        )
        out = out.loc[known].copy()

        if out.empty:
            raise ValueError(f"{path}: no mortality-known rows available.")
        labels = set(out["y_true"].astype(int).unique().tolist())
        if not labels.issubset({0, 1}):
            raise ValueError(f"{path}: non-binary mortality labels: {sorted(labels)}")
        if ((out["prediction_calibrated"] < 0) | (out["prediction_calibrated"] > 1)).any():
            raise ValueError(f"{path}: calibrated probabilities outside [0,1].")

        return out.reset_index(drop=True)

    if outcome == "los":
        required = {"prediction"}
        missing = required.difference(df.columns)
        if missing:
            raise ValueError(f"{path} missing columns: {sorted(missing)}")

        out = df[["patient_id", "stay_id", "y_true", "prediction"]].copy()
        out["y_true"] = pd.to_numeric(out["y_true"], errors="raise")
        out["prediction"] = pd.to_numeric(out["prediction"], errors="raise")
        finite = (
            np.isfinite(out["y_true"].to_numpy(dtype=float))
            & np.isfinite(out["prediction"].to_numpy(dtype=float))
        )
        if not finite.all():
            raise ValueError(f"{path}: non-finite LOS target/prediction rows.")
        if (out["y_true"] <= 0).any():
            raise ValueError(f"{path}: remaining LOS target must be > 0.")
        return out.reset_index(drop=True)

    raise ValueError(f"Unknown outcome: {outcome}")


def load_bootstrap_ci(modeling_root: Path) -> tuple[pd.DataFrame, dict]:
    bootstrap_dir = modeling_root / "bootstrap_results"
    path = bootstrap_dir / "bootstrap_metric_ci.csv"
    manifest_path = bootstrap_dir / "bootstrap_run_manifest.json"

    if not path.is_file():
        raise FileNotFoundError(
            f"{path}\nMissing bootstrap_metric_ci.csv under bootstrap_results."
        )
    if not manifest_path.is_file():
        raise FileNotFoundError(
            f"{manifest_path}\nMissing Stage-07 bootstrap manifest."
        )

    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if int(manifest.get("bootstrap_replicates", -1)) < 100:
        raise ValueError("Invalid bootstrap replicate count in Stage-07 manifest.")
    if manifest.get("mortality_probability") != "calibrated":
        raise ValueError(
            "Supplementary mortality figures require calibrated probabilities, "
            "but Stage-07 manifest is not calibrated."
        )

    df = pd.read_csv(path)
    required = {
        "metric",
        "estimate",
        "ci_low",
        "ci_high",
        "landmark_hour",
        "outcome",
        "variant",
        "cohort",
        "n",
        "valid_bootstrap_replicates",
    }
    missing = required.difference(df.columns)
    if missing:
        raise ValueError(f"bootstrap_metric_ci.csv missing columns: {sorted(missing)}")

    key = ["landmark_hour", "outcome", "variant", "cohort", "metric"]
    if df.duplicated(key).any():
        dup = df.loc[df.duplicated(key, keep=False), key]
        raise ValueError(
            "Duplicate bootstrap metric rows detected:\n"
            + dup.to_string(index=False)
        )

    numeric_cols = ["estimate", "ci_low", "ci_high"]
    if not np.isfinite(df[numeric_cols].to_numpy(dtype=float)).all():
        raise ValueError("Non-finite bootstrap estimates/CIs detected.")

    return df, manifest


