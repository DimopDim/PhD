# Plot utilities
# ---------------------------------------------------------------------
def plot_trajectory_panel(
    ax,
    ci: pd.DataFrame,
    *,
    outcome: str,
    cohort: str,
    metric: str,
    ylabel: str,
    title: str,
):
    data = ci.loc[
        ci["outcome"].eq(outcome)
        & ci["cohort"].eq(cohort)
        & ci["variant"].isin(VARIANTS)
        & metric_mask(ci, metric)
    ].copy()

    for variant in VARIANTS:
        g = data.loc[data["variant"].eq(variant)].sort_values("landmark_hour")
        if g.empty:
            continue

        x = g["landmark_hour"].to_numpy(dtype=float)
        y = g["estimate"].to_numpy(dtype=float)
        lo = g["ci_low"].to_numpy(dtype=float)
        hi = g["ci_high"].to_numpy(dtype=float)

        ax.plot(
            x,
            y,
            marker="o",
            linewidth=1.7,
            markersize=4.5,
            color=COLORS[variant],
            label=VARIANT_LABEL[variant],
        )
        ax.fill_between(
            x,
            lo,
            hi,
            alpha=0.14,
            color=COLORS[variant],
            linewidth=0,
        )

    ax.set_title(title)
    ax.set_xlabel("Landmark hour")
    ax.set_ylabel(ylabel)
    ax.set_xticks(LANDMARKS)
    ax.grid(True)
    place_legend_smart(ax)


